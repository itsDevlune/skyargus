// Opt-in: uses genuine saved cube and runs only the job created by this UI.
const {chromium,expect}=require('@playwright/test');
const {execFile}=require('child_process');
const {promisify}=require('util');
const fs=require('fs');
(async()=>{
 const root=process.env.ARGUS_BROWSER_URL||'http://127.0.0.1:8000';
 const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:1366,height:768}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(root+'/?sequence=3122bdf8-1727-44ff-ad8c-aac23cffe151');
 await page.waitForFunction(()=>window.argusTest?.state.images.size>0);
 await page.locator('#open-analysis').click();await page.locator('#real-cube-workbench > summary').click();
 await page.locator('#expand-panel').click();
 expect((await page.locator('#workspace-panel').boundingBox()).height).toBeGreaterThan(550);
 const response=page.waitForResponse(r=>r.url().endsWith('/api/v1/cubes')&&r.request().method()==='POST');
 await page.locator('#load-real-cube').click();const queued=await(await response).json();
 if(!/^[0-9a-f-]{36}$/.test(queued.job))throw Error('Expected cube job UUID');
 await promisify(execFile)('.venv313/Scripts/python.exe',['manage.py','shell','-c',`from apps.core.tasks import run_job; run_job('${queued.job}')`]);
 await expect(page.locator('#cube-coverage button')).toHaveCount(102,{timeout:30000});
 await page.waitForFunction(()=>document.querySelector('#cube-image').naturalWidth===512);
 await page.locator('#cube-channel').fill('62');await page.locator('#cube-channel').dispatchEvent('input');
 await expect(page.locator('#cube-channel-label')).toContainText('63/102');
 await page.locator('#cube-canvas').scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>document.querySelector('#cube-image').complete&&document.querySelector('#cube-image').naturalWidth===512);
 fs.mkdirSync('docs/evidence/real-cube',{recursive:true});
 await page.screenshot({path:'docs/evidence/real-cube/image-browser.png',fullPage:true});
 await page.locator('#cube-extract').click();await expect(page.locator('#cube-spectrum table tr')).toHaveCount(103,{timeout:30000});
 await expect(page.locator('#cube-spectrum')).toContainText('No propagated variance');
 await page.locator('#cube-extract-source').click();
 await expect(page.locator('#cube-extract-source')).toBeEnabled({timeout:30000});
 await expect(page.locator('#cube-spectrum table tr')).toHaveCount(103);
 const downloaded=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export cube spectrum JSON',exact:true}).click();
 await(await downloaded).saveAs('docs/evidence/real-cube/browser-spectrum.json');
 const exported=JSON.parse(fs.readFileSync('docs/evidence/real-cube/browser-spectrum.json','utf8'));
 expect(exported.measurements.length).toBe(102);
 const original=JSON.parse(fs.readFileSync('docs/evidence/real-cube/metadata.json','utf8'));
 expect(exported.cube.sha256).toBe(original.artifact.sha256);
 fs.mkdirSync('docs/evidence/real-cube',{recursive:true});
 await page.locator('#cube-spectrum').scrollIntoViewIfNeeded();await page.screenshot({path:'docs/evidence/real-cube/spectrum-browser.png',fullPage:true});
 await page.locator('#cube-channel').scrollIntoViewIfNeeded();await page.screenshot({path:'docs/evidence/real-cube/channels-browser.png',fullPage:true});
 await page.locator('#cube-b').selectOption('16');await page.locator('#cube-mode').selectOption('side');
 await expect(page.locator('#cube-view-label')).toContainText('B 17:',{timeout:30000});
 await page.locator('#cube-canvas').scrollIntoViewIfNeeded();
 await page.screenshot({path:'docs/evidence/real-cube/comparison-browser.png',fullPage:true});
 await page.locator('#cube-hits').check();await expect(page.locator('#cube-image')).toHaveAttribute('src',/coverage=1/);
 expect(errors).toEqual([]);fs.writeFileSync('docs/evidence/real-cube/browser-result.json',JSON.stringify({job:queued.job,channels:102,rows:102,errors},null,2));
 await browser.close();console.log('Genuine cached cube UI passed');
})().catch(e=>{console.error(e);process.exit(1)});
